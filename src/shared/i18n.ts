export const DICTS: Record<UiLang, Dict> = { en, tr, de, fr, es, ru };

/** What a renderer needs to translate itself: resolved language + merged dictionary. */
export interface I18nPayload {
  lang: UiLang;
  langs: { id: UiLang; label: string }[];
  dict: Record<string, string>;
}

export function i18nPayload(lang: UiLang): I18nPayload {
  return { lang, langs: UI_LANGS, dict: { ...en, ...DICTS[lang] } };
}

/** Looks up key in lang, falling back to English, then interpolates {vars}. */
export function translate(lang: UiLang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
