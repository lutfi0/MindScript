// MindScript — UI translations. English is the source language; the app
// starts in the OS language when a translation exists, English otherwise.
export type UiLang = 'en' | 'tr' | 'de' | 'fr' | 'es' | 'ru';

export const UI_LANGS: { id: UiLang; label: string }[] = [
  { id: 'en', label: 'English' },
  { id: 'tr', label: 'Türkçe' },
  { id: 'de', label: 'Deutsch' },
  { id: 'fr', label: 'Français' },
  { id: 'es', label: 'Español' },
  { id: 'ru', label: 'Русский' },
];

/** Resolves 'auto' (or an unknown value) against the OS locale. */
export function resolveUiLang(pref: string, systemLocale: string): UiLang {
  if ((UI_LANGS as { id: string }[]).some((l) => l.id === pref)) return pref as UiLang;
  const short = (systemLocale || '').toLowerCase().split(/[-_]/)[0];
  const hit = UI_LANGS.find((l) => l.id === short);
  return hit ? hit.id : 'en';
}

